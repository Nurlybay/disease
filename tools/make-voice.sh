#!/usr/bin/env bash
# Генерация реплик пациента: edge-tts, нейронный голос ru-RU-DmitryNeural.
# Требует: python3 c пакетом edge-tts (pip install edge-tts), ffmpeg,
# и сеть — но только на время генерации: сайт в рантайме остаётся офлайн,
# mp3 лежат в репозитории. Сервис Microsoft бесплатный, ключей не нужно.
#
# Раньше здесь был macOS `say` с единственным русским голосом — женской
# Milena, сдвинутой в мужской диапазон (asetrate*0.84 + atempo). Дмитрий —
# настоящий мужской голос, поэтому сдвиг тона убран; полосовая фильтрация,
# паузы и loudnorm оставлены, чтобы громкость реплик не разъехалась с
# аудио аускультации.
#
# Идемпотентно: перезапуск просто перезаписывает mp3 теми же настройками.
# Имена файлов должны совпадать с полями `audio` в site/cases/*.js —
# если реплика добавлена в случай, но не здесь, пациент просто промолчит.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=site/media/voice
mkdir -p "$OUT"

VOICE=ru-RU-DmitryNeural
RATE="-6%"            # чуть медленнее нейтрального: пациент не диктор

python3 -m edge_tts --list-voices >/dev/null 2>&1 || {
  echo "edge-tts не найден. Установите: python3 -m pip install --user edge-tts" >&2
  exit 1
}

say_line() {
  local name="$1" text="$2"
  python3 -m edge_tts --voice "$VOICE" --rate="$RATE" \
    --text "$text" --write-media /tmp/_v.mp3 >/dev/null
  ffmpeg -y -v error -i /tmp/_v.mp3 -af \
    "highpass=f=85,lowpass=f=8200,adelay=250|250,apad=pad_dur=0.5,loudnorm=I=-16:TP=-1.5:LRA=11" \
    -ar 44100 -ac 1 -b:a 128k "$OUT/$name.mp3"
  printf '  %-14s %5.2fs  %s\n' "$name" \
    "$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$OUT/$name.mp3")" "$text"
}

echo "Приветствие:"
say_line greeting  "Добрый день, доктор. Можете меня осмотреть? У меня появился небольшой кашель."

echo "Служебные реплики:"
say_line sys-unknown    "Извините, доктор, я не понял вопроса."
say_line sys-deepbreath "Хорошо, доктор. Дышу глубоко, через рот."
say_line sys-cough      "Кхе, кхе. Вот, покашлял."
say_line sys-mouth      "Аааа."

echo "Паспортные и социальные данные:"
say_line p-name    "Абенов Мурат Сапарович."
say_line p-age     "Мне тридцать четыре года."
say_line p-job     "Работаю сварщиком на заводе, уже двенадцать лет. Дыма и пыли на участке хватает, респиратор надеваю не всегда."
say_line p-living  "Живу в частном доме с женой и двумя детьми. Отопление угольное, в доме сыровато, зимой холодно."
say_line p-allergy "Аллергии ни на что нет. Антибиотики раньше переносил нормально, сыпи не было."
say_line p-family  "Отец умер от болезни лёгких, он много курил. У младшей сестры бронхиальная астма с детства."
say_line p-habits  "Вредных привычек нет. Алкоголь только по праздникам, немного. Наркотики никогда не пробовал."
say_line p-tb      "В тюрьме не был, с туберкулёзными не общался. За границу не выезжал. Никто из знакомых не болел, насколько знаю."

echo "Расспрос:"
say_line q-cough    "Кашель почти постоянный. Утром особенно — пока не откашляюсь, нормально дышать не могу."
say_line duration   "Кашель у меня уже давно, месяцев восемь, а может и больше. Сильнее всего с утра."
say_line sputum     "Мокроты много. Каждое утро откашливаю почти полстакана. Густая, желтовато-зелёная, с неприятным запахом."
say_line blood      "Раза два были прожилки крови в мокроте. Я испугался, но потом само прошло."
say_line smoking    "Нет, доктор, я не курю. Никогда не курил."
say_line fever      "Высокой температуры нет. Иногда к вечеру тридцать семь и два, не больше."
say_line dyspnea    "Когда поднимаюсь на третий этаж, начинаю задыхаться. Раньше такого не было."
say_line weight     "За полгода похудел килограммов на пять. Аппетита совсем нет."
say_line antibiotic "Несколько раз пил антибиотики. Становилось легче на пару недель, потом всё возвращалось."
say_line night      "Ночью кашель будит, особенно если лягу на правый бок."
say_line history    "В детстве я долго лежал в больнице с тяжёлым воспалением лёгких. С тех пор кашляю почти постоянно."
say_line q-hospital "В больнице лежал раза три с воспалением лёгких. Последний раз — года два назад, недели две прокапали."
say_line q-flu      "Флюорографию делал год назад. Сказали, есть какие-то изменения в лёгких, велели дообследоваться, а я не пошёл."
say_line q-sinus    "Нос почти всё время заложен, дышу ртом. Гайморит был два раза, прокалывали."
say_line q-sweat    "Ночью потею, бывает — майку приходится менять."
say_line q-wheeze   "Свиста нет, а вот клокотание в груди сам слышу, особенно утром. Как будто там что-то переливается."
say_line q-chestpain "Иногда покалывает в боку справа, когда сильно раскашляюсь. Постоянных болей нет."
say_line q-fatigue  "Быстро устаю. К вечеру совсем сил нет, хотя работа не тяжелее, чем раньше."
say_line q-meds     "Постоянно ничего не принимаю. Только сироп от кашля в аптеке покупаю, когда совсем замучает."
say_line q-vaccine  "От гриппа не прививался никогда. Про прививку от пневмонии впервые слышу."

echo "Готово."
