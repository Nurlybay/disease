#!/usr/bin/env bash
# Генерация реплик пациентов: edge-tts, нейронные голоса Microsoft.
# Требует: python3 (edge-tts ставится сам в tools/.venv), ffmpeg и сеть —
# но только на время генерации: сайт в рантайме остаётся офлайн, mp3 лежат
# в репозитории. Сервис бесплатный, ключей не нужно.
#
# Один персонаж — одна функция и один каталог site/media/voice/<id>/.
# Голос, темп и тон подбираются под возраст и пол персонажа. Имена файлов
# должны совпадать с полями `audio` в site/characters/<id>.js — если
# реплика есть в случае, но не здесь, пациент просто промолчит.
#
# Запуск:
#   bash tools/make-voice.sh <id-персонажа>   один персонаж
#   bash tools/make-voice.sh new              три новых (без Абенова)
#   bash tools/make-voice.sh all              все, включая перегенерацию Абенова
#
# Идемпотентно: перезапуск перезаписывает mp3 теми же настройками.
set -euo pipefail
cd "$(dirname "$0")/.."

# Homebrew-python управляется извне (PEP 668), поэтому edge-tts живёт в
# собственном venv рядом со скриптом. Создаётся один раз, в git не попадает.
VENV=tools/.venv
PY="$VENV/bin/python3"
if ! "$PY" -m edge_tts --help >/dev/null 2>&1; then
  echo "Ставлю edge-tts в $VENV..."
  python3 -m venv "$VENV"
  "$PY" -m pip install --quiet edge-tts
fi

# Полосовая фильтрация, паузы и loudnorm — чтобы громкость реплик не
# разъезжалась с аудио аускультации. Использует текущие OUT/VOICE/RATE/PITCH.
#
# Бесплатный сервис edge-tts иногда зависает на запросе или отдаёт обрезанный
# файл, поэтому: сторожевой таймер 45 с, до трёх попыток и проверка, что
# длительность правдоподобна для длины текста (~1 с на 40 символов минимум).
say_line() {
  local name="$1" text="$2" try pid waited dur min
  for try in 1 2 3; do
    rm -f /tmp/_v.mp3
    "$PY" -m edge_tts --voice "$VOICE" --rate="$RATE" --pitch="$PITCH" \
      --text "$text" --write-media /tmp/_v.mp3 >/dev/null 2>&1 &
    pid=$!
    waited=0
    while kill -0 "$pid" 2>/dev/null && [ "$waited" -lt 45 ]; do
      sleep 1; waited=$((waited + 1))
    done
    if kill -0 "$pid" 2>/dev/null; then
      kill "$pid" 2>/dev/null || true
      wait "$pid" 2>/dev/null || true
      echo "  $name: edge-tts завис (>45 c), попытка $try из 3" >&2
      continue
    fi
    wait "$pid" || { echo "  $name: ошибка edge-tts, попытка $try из 3" >&2; continue; }
    [ -s /tmp/_v.mp3 ] || { echo "  $name: пустой ответ, попытка $try из 3" >&2; continue; }
    dur=$(ffprobe -v error -show_entries format=duration -of csv=p=0 /tmp/_v.mp3)
    min=$(( ${#text} / 40 + 1 ))
    if [ "${dur%.*}" -lt "$min" ] 2>/dev/null; then
      echo "  $name: файл обрезан (${dur}s на ${#text} символов), попытка $try из 3" >&2
      continue
    fi
    ffmpeg -y -v error -i /tmp/_v.mp3 -af \
      "highpass=f=85,lowpass=f=8200,adelay=250|250,apad=pad_dur=0.5,loudnorm=I=-16:TP=-1.5:LRA=11" \
      -ar 44100 -ac 1 -b:a 128k "$OUT/$name.mp3"
    printf '  %-14s %5.2fs  %s\n' "$name" \
      "$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$OUT/$name.mp3")" "$text"
    return 0
  done
  echo "!! $name: три попытки подряд неудачны — проверьте сеть и перезапустите" >&2
  return 1
}

